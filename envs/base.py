"""Shared environment interface.

Every environment is a SEQUENTIAL EVIDENCE-ACCUMULATION task with a hidden
parameter (rule / arm quality / opponent type) fixed for the whole session.
The model never plays into the history: history is generated by a SCRIPTED
behavior policy, and at every round t the model is asked, as an observer-decider,
what the optimal action is NOW given the accumulated evidence. This keeps the
evidence stream identical across models and probes, so trajectories are directly
comparable.

Semantic actions:
    act0 : the conservative / default option   (STAY, LEFT, HARE, DEFECT, KEEP)
    act1 : the evidence-sensitive option       (SWITCH, RIGHT, STAG, COOPERATE, INVEST)

Required methods:
    new_round(t)              -> dict of prompt variables for the current round
    behavior_action(t)        -> semantic action index (0/1) the scripted history
                                 player takes this round
    outcome(t, ctx, a)        -> (reward, record) sampled under the hidden parameter
    format_history(records)   -> string block for the prompt (dict-list + tally)
    oracle_p_act1(records)    -> normative P(act1 optimal | records)  in [0,1]
"""


