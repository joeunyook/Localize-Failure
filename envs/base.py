def tally_block(records, act0, act1):
    if not records:
        return "[]  # no completed rounds yet"
    lines = ["["]
    for r in records:
        lines.append(f'    {{"action": "{r["action"]}", "result": "{r["result"]}"}},')
    lines.append("]")
    a1w = sum(1 for r in records if r["action"] == act1 and r["win"])
    a1l = sum(1 for r in records if r["action"] == act1 and not r["win"])
    a0w = sum(1 for r in records if r["action"] == act0 and r["win"])
    a0l = sum(1 for r in records if r["action"] == act0 and not r["win"])
    lines.append(f"# Tally  ->  {act1}: {a1w} WON / {a1l} LOST  |  {act0}: {a0w} WON / {a0l} LOST")
    return "\n".join(lines)
